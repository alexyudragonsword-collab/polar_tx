def _iverilog_run(outdir: str, sources: list[str], top_vvp: str) -> str | None:
    import shutil
    import subprocess
    if shutil.which("iverilog") is None:
        return None
    subprocess.run(["iverilog", "-g2012", "-o", top_vvp, *sources],
                   cwd=outdir, check=True)
    out = subprocess.run(["vvp", top_vvp], cwd=outdir, check=True,
                        capture_output=True, text=True)
    return out.stdout


def verify_thermo_decoder(outdir: str) -> str | None:
    return _iverilog_run(outdir, ["dpa_thermo_decode.v",
                                  "tb_dpa_thermo_decode.v"], "tb_thermo.vvp")


def verify_cfr_clip(outdir: str) -> str | None:
    return _iverilog_run(outdir, ["cfr_clip.v", "tb_cfr_clip.v"], "tb_cfr.vvp")


def verify_phase_acc(outdir: str) -> str | None:
    return _iverilog_run(outdir, ["dtc_phase_acc.v", "tb_dtc_phase_acc.v"],
                         "tb_phase_acc.vvp")


def emit_datapath(dpa, outdir: str, *, dpd=None) -> dict:
    """Emit the full digital polar-TX datapath + AMS PA model in one dir:
    CFR clip -> DPD LUT (optional) -> DPA thermo decoder -> RNM DPA, plus
    the DTC phase-accumulator datapath.  Returns all written paths."""
    paths = {}
    paths.update(emit_cfr_clip_rtl(outdir))
    paths.update(emit_phase_acc_rtl(outdir))
    paths.update(emit_thermo_decoder_rtl(dpa.cfg, outdir))
    paths.update(emit_dpa_rnm_vams(dpa, outdir))
    if dpd is not None:
        paths.update(emit_dpd_rtl(quantize_dpd_luts(dpd), outdir))
    return paths
