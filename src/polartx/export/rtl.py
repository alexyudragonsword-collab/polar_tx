def dpa_rnm_selfcheck(dpa, outdir: str) -> dict:
    """Verify the baked RNM LUTs reproduce the DPA tables at zero tolerance
    (the AMS analogue of the iverilog golden check)."""
    amp = np.loadtxt(os.path.join(outdir, "dpa_amp_real.memh"))
    ph = np.loadtxt(os.path.join(outdir, "dpa_ampm_real.memh"))
    amp_err = float(np.max(np.abs(amp - dpa.amp_table)))
    ph_err = float(np.max(np.abs(ph - dpa.phase_table)))
    return {"amp_max_err": amp_err, "ph_max_err": ph_err,
            "ok": amp_err < 1e-8 and ph_err < 1e-8}


